import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "@vue/compiler-dom";

const root = fileURLToPath(new URL("../", import.meta.url));
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  console.error("Usage: node scripts/vendor-assets.mjs [--check]");
  process.exit(2);
}
const check = args[0] === "--check";
const assets = [
  ["vue/dist/vue.runtime.global.prod.js", "js/vue.min.js"],
  ["@materializecss/materialize/dist/js/materialize.min.js", "js/materialize.min.js"],
  ["@materializecss/materialize/dist/css/materialize.min.css", "css/vendor/materialize.min.css"],
];

async function output(destination, content) {
  const target = resolve(root, "internal/server/webrootSrc", destination);
  if (check) {
    const existing = await readFile(target).catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (!existing || !content.equals(existing)) {
      console.error(`Stale or missing asset: ${destination}. Run npm run vendor and commit the result.`);
      process.exitCode = 1;
    }
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
    console.log(`Copied ${destination}`);
  }
}

for (const [source, destination] of assets) {
  await output(destination, await readFile(resolve(root, "node_modules", source)));
}

// Compile the in-DOM template ahead of time: the runtime compiler needs eval,
// which the application's script-src 'self' policy intentionally disallows.
const html = await readFile(resolve(root, "internal/server/webrootSrc/index.html"), "utf8");
const start = '<div id="app">';
const end = '</div> <!-- end of app -->';
if (html.split(start).length !== 2 || html.split(end).length !== 2) {
  throw new Error("Expected one #app template and its end-of-app marker in index.html");
}
const template = html.slice(html.indexOf(start) + start.length, html.indexOf(end));
const { code } = compile(template, { mode: "function", prefixIdentifiers: true });
await output("js/app-render.js", Buffer.from(
  "// Generated by npm run vendor from index.html. Do not edit.\n" +
  `var TraefikAdminRender = (() => {\n${code}\n})();\n`,
));
if (check && !process.exitCode) console.log("Embedded assets match the installed packages.");
